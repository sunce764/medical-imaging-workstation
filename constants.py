# 见 experiments/seg_validate.py 与 results/seg_dice.csv（s0029，21 器官均 Dice≈0.92）。
#
# 【本表两处修订的实测依据】
#   1. 肺叶左右曾配反：旧表按「红橙=右、蓝青=左」上色，但实测 10,11=【左】肺
#      上/下叶、12,13,14=【右】肺上/中/下叶（放射惯例镜像所致的旧误判）。现已
#      按真实侧别重新分配：左肺=蓝青族，右肺=红橙族。
#   2. 旧表只给 16 个类配色，其余落暗灰并注为「基本不出现」——实测证伪：
#      s0029 一例中 2,3,4,7,8,9,17 全部在场，且右肾 Dice=0.985、左肾 0.977
#      （仅次于肺叶），却与胆囊/胰腺/双侧肾上腺/甲状腺同渲染为一种暗灰，
#      相邻器官边界不可辨。现补齐全部 24 类。
#
# 配色约定：同一解剖系统同色族、以明度区分个体；左右成对器官取邻近色调，
# 既能一眼归组，又不至于混为一体。
# =============================================================================
